#!/usr/bin/env python3
"""
ROS2-UGV Custom Serial Protocol Code Generator (ADR-0003)
Reads protocol_def.yaml and generates:
  - C headers: protocol/c/ugv_protocol.h
  - C++ headers: protocol/cpp/ugv_protocol.hpp
  - Python codec: protocol/ugv_protocol.py
"""

import os
import re
import sys
from pathlib import Path
import yaml

TYPE_MAP_C = {
    "uint8": "uint8_t",
    "int8": "int8_t",
    "uint16": "uint16_t",
    "int16": "int16_t",
    "uint32": "uint32_t",
    "int32": "int32_t",
    "float": "float",
    "double": "double",
}

TYPE_SIZE = {
    "uint8": 1,
    "int8": 1,
    "uint16": 2,
    "int16": 2,
    "uint32": 4,
    "int32": 4,
    "float": 4,
    "double": 8,
}

TYPE_MAP_PY = {
    "uint8": "B",
    "int8": "b",
    "uint16": "H",
    "int16": "h",
    "uint32": "I",
    "int32": "i",
    "float": "f",
    "double": "d",
}


def parse_type(type_str):
    arr_match = re.match(r"^([a-zA-Z0-9_]+)\[(\d+)\]$", type_str)
    if arr_match:
        base_type = arr_match.group(1)
        length = int(arr_match.group(2))
        return base_type, length
    return type_str, None


def get_field_size(type_str):
    base, length = parse_type(type_str)
    if base == "char":
        return length if length else 1
    base_size = TYPE_SIZE.get(base, 1)
    return base_size * length if length else base_size


def to_snake_case(name):
    s1 = re.sub("(.)([A-Z][a-z]+)", r"\1_\2", name)
    return re.sub("([a-z0-9])([A-Z])", r"\1_\2", s1).lower()


def to_screaming_snake(name):
    return to_snake_case(name).upper()


def generate_c_header(spec, output_path):
    version = spec.get("protocol_version", 1)
    enums = spec.get("enums", {})
    messages = spec.get("messages", [])

    lines = [
        "/* Auto-generated by protocol/codegen.py. DO NOT EDIT! */",
        f"/* Protocol Version: {version} (ADR-0003) */",
        "#ifndef UGV_PROTOCOL_H",
        "#define UGV_PROTOCOL_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#include <stdbool.h>",
        '#include "ugv_protocol/frame.h"',
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        f"#define UGV_PROTOCOL_VERSION {version}U",
        "",
    ]

    # Enums
    lines.append("/* Enums */")
    for enum_name, enum_info in enums.items():
        c_enum_name = f"ugv_{to_snake_case(enum_name)}_t"
        lines.append(f"/* {enum_info.get('description', '')} */")
        lines.append("typedef enum {")
        for val_name, val in enum_info["values"].items():
            if isinstance(val, int):
                val_str = f"0x{val:04X}U" if val > 9 else f"{val}U"
            else:
                val_str = str(val)
            lines.append(f"    UGV_{to_screaming_snake(enum_name)}_{val_name} = {val_str},")
        lines.append(f"}} {c_enum_name};")
        lines.append("")

    # Compatibility aliases
    lines.append("/* Compatibility aliases */")
    lines.append("typedef ugv_system_status_t ugv_system_status_flags_t;")
    lines.append("#define UGV_SYSTEM_STATUS_FLAGS_FLAG_ESTOP_ACTIVE UGV_SYSTEM_STATUS_ESTOP_ACTIVE")
    lines.append("#define UGV_SYSTEM_STATUS_FLAGS_FLAG_FAILSAFE_ACTIVE UGV_SYSTEM_STATUS_FAILSAFE_ACTIVE")
    lines.append("#define UGV_SYSTEM_STATUS_FLAGS_FLAG_LOW_BATTERY UGV_SYSTEM_STATUS_LOW_BATTERY")
    lines.append("#define UGV_SYSTEM_STATUS_FLAGS_FLAG_IMU_READY UGV_SYSTEM_STATUS_IMU_READY")
    lines.append("#define UGV_SYSTEM_STATUS_FLAGS_FLAG_HEADING_MISMATCH UGV_SYSTEM_STATUS_HEADING_MISMATCH")
    lines.append("#define UGV_SYSTEM_STATUS_FLAGS_FLAG_MOTOR_OVERCURRENT UGV_SYSTEM_STATUS_MOTOR_OVERCURRENT")
    lines.append("#define UGV_SYSTEM_STATUS_FLAGS_FLAG_COMM_TIMEOUT UGV_SYSTEM_STATUS_COMM_TIMEOUT")
    lines.append("")

    # Message IDs
    lines.append("/* Message IDs */")
    lines.append("typedef enum {")
    for msg in messages:
        msg_id_hex = f"0x{msg['id']:02X}U"
        lines.append(f"    UGV_MSG_{to_screaming_snake(msg['name'])} = {msg_id_hex}, /* {msg['direction']} */")
    lines.append("} ugv_msg_id_t;")
    lines.append("")

    # Common Header
    lines.extend([
        "/* Common Message Header (10 bytes packed) */",
        "typedef struct __attribute__((packed)) {",
        "    uint8_t msg_id;        /* ugv_msg_id_t */",
        "    uint8_t reserved;      /* byte alignment */",
        "    uint32_t seq;          /* packet sequence counter */",
        "    uint32_t timestamp_us; /* microsecond timestamp (MCU clock) */",
        "} ugv_msg_header_t;",
        "",
    ])

    # Message Structs
    lines.append("/* Message Payloads */")
    for msg in messages:
        struct_name = f"ugv_msg_{to_snake_case(msg['name'])}_t"
        lines.append(f"/* ID 0x{msg['id']:02X}: {msg.get('description', '')} */")
        lines.append("typedef struct __attribute__((packed)) {")
        lines.append("    ugv_msg_header_t header;")
        for field in msg["fields"]:
            fname = field["name"]
            ftype = field["type"]
            base, length = parse_type(ftype)
            c_type = TYPE_MAP_C.get(base, base)
            if base == "char":
                c_type = "char"
            if length:
                lines.append(f"    {c_type} {fname}[{length}];")
            else:
                lines.append(f"    {c_type} {fname};")
        lines.append(f"}} {struct_name};")
        lines.append("")

    # Union of all messages
    lines.append("/* Union of all valid message structures */")
    lines.append("typedef union {")
    lines.append("    ugv_msg_header_t header;")
    for msg in messages:
        lines.append(f"    ugv_msg_{to_snake_case(msg['name'])}_t {to_snake_case(msg['name'])};")
    lines.append("} ugv_msg_payload_t;")
    lines.append("")

    # Maximum payload size
    lines.append("/* Maximum payload size */")
    lines.append(f"#define UGV_MAX_PAYLOAD_SIZE (sizeof(ugv_msg_payload_t))")
    lines.append(f"#define UGV_MAX_FRAME_SIZE   FRAME_MAX_ENCODED(UGV_MAX_PAYLOAD_SIZE)")
    lines.append("")

    # Helper Functions
    lines.extend([
        "/* Helper Encode Functions */",
        "static inline size_t ugv_encode_frame(const void *msg_struct, size_t msg_size, uint8_t *out_frame)",
        "{",
        "    return frame_encode((const uint8_t *)msg_struct, msg_size, out_frame);",
        "}",
        "",
        "/* Decode in-place: frame_buf contains raw bytes ending with 0x00 */",
        "static inline int ugv_decode_frame(uint8_t *frame_buf, size_t frame_len, ugv_msg_payload_t *out_msg)",
        "{",
        "    int payload_len = frame_decode(frame_buf, frame_len);",
        "    if (payload_len < (int)sizeof(ugv_msg_header_t)) {",
        "        return -1;",
        "    }",
        "    if (payload_len > (int)sizeof(ugv_msg_payload_t)) {",
        "        return -1;",
        "    }",
        "    if (out_msg != NULL) {",
        "        uint8_t *dst = (uint8_t *)out_msg;",
        "        for (int i = 0; i < payload_len; i++) {",
        "            dst[i] = frame_buf[i];",
        "        }",
        "    }",
        "    return payload_len;",
        "}",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* UGV_PROTOCOL_H */",
        "",
    ])

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated C header: {output_path}")


def generate_cpp_header(spec, output_path):
    version = spec.get("protocol_version", 1)
    enums = spec.get("enums", {})
    messages = spec.get("messages", [])

    lines = [
        "// Auto-generated by protocol/codegen.py. DO NOT EDIT!",
        f"// Protocol Version: {version} (ADR-0003)",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <cstddef>",
        "#include <cstring>",
        "#include <array>",
        "#include <vector>",
        "#include <functional>",
        "#include <optional>",
        '#include "ugv_protocol/frame.h"',
        "",
        "namespace ugv::protocol {",
        "",
        f"inline constexpr uint16_t PROTOCOL_VERSION = {version};",
        "",
    ]

    # Enums
    lines.append("// Scoped Enums")
    for enum_name, enum_info in enums.items():
        base_t = enum_info.get("type", "uint8")
        cpp_base_t = TYPE_MAP_C.get(base_t, "uint8_t")
        lines.append(f"// {enum_info.get('description', '')}")
        lines.append(f"enum class {enum_name} : {cpp_base_t} {{")
        for val_name, val in enum_info["values"].items():
            val_str = f"0x{val:04X}" if isinstance(val, int) and val > 9 else str(val)
            lines.append(f"    {val_name} = {val_str},")
        lines.append("};")
        lines.append("")

    # Compatibility aliases
    lines.append("// Compatibility aliases")
    lines.append("using SystemStatusFlags = SystemStatus;")
    lines.append("")

    # Message IDs
    lines.append("enum class MessageId : uint8_t {")
    for msg in messages:
        lines.append(f"    {msg['name']} = 0x{msg['id']:02X},")
    lines.append("};")
    lines.append("")

    # Common Header
    lines.extend([
        "#pragma pack(push, 1)",
        "struct Header {",
        "    uint8_t msg_id{0};",
        "    uint8_t reserved{0};",
        "    uint32_t seq{0};",
        "    uint32_t timestamp_us{0};",
        "};",
        "",
    ])

    # Message Structs
    for msg in messages:
        lines.append(f"// ID 0x{msg['id']:02X}: {msg.get('description', '')}")
        lines.append(f"struct {msg['name']} {{")
        lines.append(f"    Header header{{static_cast<uint8_t>(MessageId::{msg['name']}), 0, 0, 0}};")
        for field in msg["fields"]:
            fname = field["name"]
            ftype = field["type"]
            base, length = parse_type(ftype)
            c_type = TYPE_MAP_C.get(base, base)
            if base == "char":
                c_type = "char"
            if length:
                lines.append(f"    {c_type} {fname}[{length}]{{}};")
            else:
                lines.append(f"    {c_type} {fname}{{0}};")
        lines.append("};")
        lines.append("")

    lines.extend([
        "#pragma pack(pop)",
        "",
    ])

    # Codec helper class
    lines.extend([
        "/// Encode message to byte vector with COBS framing and CRC16",
        "template <typename T>",
        "inline std::vector<uint8_t> encode(const T& msg) {",
        "    std::vector<uint8_t> out(FRAME_MAX_ENCODED(sizeof(T)));",
        "    size_t len = frame_encode(reinterpret_cast<const uint8_t*>(&msg), sizeof(T), out.data());",
        "    out.resize(len);",
        "    return out;",
        "}",
        "",
        "/// Streaming parser for serial stream",
        "class PacketParser {",
        "public:",
        "    explicit PacketParser(size_t max_buf_size = 512) : buf_(max_buf_size) {}",
        "",
        "    template <typename Callback>",
        "    void parse_byte(uint8_t b, Callback&& on_packet) {",
        "        if (b == 0x00) {",
        "            if (write_idx_ > 0) {",
        "                int payload_len = frame_decode(buf_.data(), write_idx_);",
        "                if (payload_len >= static_cast<int>(sizeof(Header))) {",
        "                    const auto* hdr = reinterpret_cast<const Header*>(buf_.data());",
        "                    on_packet(static_cast<MessageId>(hdr->msg_id), buf_.data(), static_cast<size_t>(payload_len));",
        "                }",
        "                write_idx_ = 0;",
        "            }",
        "        } else {",
        "            if (write_idx_ < buf_.size()) {",
        "                buf_[write_idx_++] = b;",
        "            } else {",
        "                // Overflow, reset buffer",
        "                write_idx_ = 0;",
        "            }",
        "        }",
        "    }",
        "",
        "    template <typename Callback>",
        "    void parse_chunk(const uint8_t* data, size_t size, Callback&& on_packet) {",
        "        for (size_t i = 0; i < size; ++i) {",
        "            parse_byte(data[i], on_packet);",
        "        }",
        "    }",
        "",
        "    void reset() { write_idx_ = 0; }",
        "",
        "private:",
        "    std::vector<uint8_t> buf_;",
        "    size_t write_idx_{0};",
        "};",
        "",
        "} // namespace ugv::protocol",
        "",
    ])

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated C++ header: {output_path}")


def generate_python_module(spec, output_path):
    version = spec.get("protocol_version", 1)
    enums = spec.get("enums", {})
    messages = spec.get("messages", [])

    lines = [
        '"""Auto-generated by protocol/codegen.py. DO NOT EDIT!"""',
        f"PROTOCOL_VERSION = {version}",
        "import struct",
        "from enum import IntEnum",
        "",
    ]

    # CRC16-CCITT and COBS implementation in pure python
    lines.extend([
        "def crc16_ccitt(data: bytes, crc: int = 0xFFFF) -> int:",
        "    for b in data:",
        "        crc ^= (b << 8)",
        "        for _ in range(8):",
        "            if crc & 0x8000:",
        "                crc = ((crc << 1) ^ 0x1021) & 0xFFFF",
        "            else:",
        "                crc = (crc << 1) & 0xFFFF",
        "    return crc",
        "",
        "def cobs_encode(data: bytes) -> bytes:",
        "    out = bytearray()",
        "    code_idx = 0",
        "    out.append(1)",
        "    code = 1",
        "    for b in data:",
        "        if b != 0:",
        "            out.append(b)",
        "            code += 1",
        "        if b == 0 or code == 0xFF:",
        "            out[code_idx] = code",
        "            code_idx = len(out)",
        "            out.append(1)",
        "            code = 1",
        "    out[code_idx] = code",
        "    out.append(0)",
        "    return bytes(out)",
        "",
        "def cobs_decode(frame: bytes) -> bytes:",
        "    # frame without trailing 0x00",
        "    out = bytearray()",
        "    idx = 0",
        "    n = len(frame)",
        "    while idx < n:",
        "        code = frame[idx]",
        "        idx += 1",
        "        if code == 0 or idx + code - 1 > n:",
        "            raise ValueError('Invalid COBS code')",
        "        for _ in range(code - 1):",
        "            out.append(frame[idx])",
        "            idx += 1",
        "        if code != 0xFF and idx < n:",
        "            out.append(0)",
        "    return bytes(out)",
        "",
        "def frame_encode(payload: bytes) -> bytes:",
        "    crc = crc16_ccitt(payload, 0xFFFF)",
        "    data_with_crc = payload + struct.pack('<H', crc)",
        "    return cobs_encode(data_with_crc)",
        "",
        "def frame_decode(frame_without_zero: bytes) -> bytes:",
        "    raw = cobs_decode(frame_without_zero)",
        "    if len(raw) < 2:",
        "        raise ValueError('Frame too short')",
        "    payload = raw[:-2]",
        "    expected_crc = struct.unpack('<H', raw[-2:])[0]",
        "    actual_crc = crc16_ccitt(payload, 0xFFFF)",
        "    if expected_crc != actual_crc:",
        "        raise ValueError(f'CRC mismatch: expected {expected_crc:#06x}, got {actual_crc:#06x}')",
        "    return payload",
        "",
    ])

    # Enums
    for enum_name, enum_info in enums.items():
        lines.append(f"class {enum_name}(IntEnum):")
        for val_name, val in enum_info["values"].items():
            lines.append(f"    {val_name} = {val}")
        lines.append("")

    # Compatibility aliases
    lines.append("# Compatibility aliases")
    lines.append("SystemStatusFlags = SystemStatus")
    lines.append("")

    # Message IDs
    lines.append("class MessageId(IntEnum):")
    for msg in messages:
        lines.append(f"    {msg['name']} = {msg['id']}")
    lines.append("")

    # Message Classes
    for msg in messages:
        struct_fmt = "<BBII"  # msg_id (B), reserved (B), seq (I), timestamp_us (I)
        field_names = ["seq", "timestamp_us"]
        for f in msg["fields"]:
            fname = f["name"]
            ftype = f["type"]
            base, length = parse_type(ftype)
            field_names.append(fname)
            if base == "char":
                struct_fmt += f"{length}s"
            elif length:
                py_fmt = TYPE_MAP_PY.get(base, "B")
                struct_fmt += f"{length}{py_fmt}"
            else:
                py_fmt = TYPE_MAP_PY.get(base, "B")
                struct_fmt += py_fmt

        lines.append(f"class {msg['name']}:")
        lines.append(f"    MSG_ID = MessageId.{msg['name']}")
        lines.append(f"    STRUCT_FMT = '{struct_fmt}'")
        lines.append(f"    PAYLOAD_SIZE = struct.calcsize(STRUCT_FMT)")
        lines.append("")
        args = ", ".join([f"{n}=0" if not n.endswith("uid") and not n.endswith("message") else f"{n}=b''" for n in field_names])
        lines.append(f"    def __init__(self, {args}):")
        for n in field_names:
            lines.append(f"        self.{n} = {n}")
        lines.append("")
        lines.append("    def pack(self) -> bytes:")
        pack_args = ["self.MSG_ID", "0", "self.seq", "self.timestamp_us"]
        for f in msg["fields"]:
            fname = f["name"]
            ftype = f["type"]
            base, length = parse_type(ftype)
            if base == "char":
                pack_args.append(f"(self.{fname}.encode('ascii') if isinstance(self.{fname}, str) else self.{fname})[:{length}].ljust({length}, b'\\x00')")
            elif length:
                pack_args.append(f"*self.{fname}")
            else:
                pack_args.append(f"self.{fname}")
        lines.append(f"        return struct.pack(self.STRUCT_FMT, {', '.join(pack_args)})")
        lines.append("")
        lines.append("    @classmethod")
        lines.append("    def unpack(cls, data: bytes):")
        lines.append("        unpacked = struct.unpack(cls.STRUCT_FMT, data)")
        lines.append("        # unpacked[0] is msg_id, unpacked[1] is reserved")
        lines.append("        seq = unpacked[2]")
        lines.append("        ts = unpacked[3]")
        idx = 4
        inst_args = ["seq=seq", "timestamp_us=ts"]
        for f in msg["fields"]:
            fname = f["name"]
            ftype = f["type"]
            base, length = parse_type(ftype)
            if base == "char":
                inst_args.append(f"{fname}=unpacked[{idx}].decode('ascii', errors='ignore').rstrip('\\x00')")
                idx += 1
            elif length:
                inst_args.append(f"{fname}=unpacked[{idx}:{idx+length}]")
                idx += length
            else:
                inst_args.append(f"{fname}=unpacked[{idx}]")
                idx += 1
        lines.append(f"        return cls({', '.join(inst_args)})")
        lines.append("")
        lines.append("    def encode_frame(self) -> bytes:")
        lines.append("        return frame_encode(self.pack())")
        lines.append("")

    # Decoder / Dispatcher
    lines.extend([
        "DISPATCH_MAP = {",
    ])
    for msg in messages:
        lines.append(f"    MessageId.{msg['name']}: {msg['name']},")
    lines.extend([
        "}",
        "",
        "def decode_message(payload: bytes):",
        "    if len(payload) < 10:",
        "        raise ValueError('Payload smaller than header size')",
        "    msg_id = payload[0]",
        "    cls = DISPATCH_MAP.get(msg_id)",
        "    if cls is None:",
        "        raise ValueError(f'Unknown msg_id: {msg_id:#04x}')",
        "    return cls.unpack(payload)",
        "",
        "def decode_frame_stream(frame_bytes: bytes):",
        "    payload = frame_decode(frame_bytes)",
        "    return decode_message(payload)",
        "",
    ])

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated Python module: {output_path}")


def main():
    root = Path(__file__).resolve().parent
    spec_path = root / "protocol_def.yaml"
    if not spec_path.exists():
        print(f"Error: Spec file not found at {spec_path}", file=sys.stderr)
        sys.exit(1)

    with open(spec_path, "r", encoding="utf-8") as f:
        spec = yaml.safe_load(f)

    c_out = root / "c" / "ugv_protocol.h"
    cpp_out = root / "cpp" / "ugv_protocol.hpp"
    py_out = root / "ugv_protocol.py"

    generate_c_header(spec, c_out)
    generate_cpp_header(spec, cpp_out)
    generate_python_module(spec, py_out)
    print("Code generation completed successfully.")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Solve Vehkernel's layered Kconfig configuration (ADR-0017).

Fragments are merged in order (MCU or SITL defaults, board defaults, debug
overlays). After each merge every assignment from that fragment must have
taken effect; one that did not, for example because a dependency is not met,
is an error naming the fragment, line and unmet dependency.

Subcommands:

    generate    write .config, vk/config.h and kconfig.cmake
    menuconfig  edit the configuration interactively and store the changes
                relative to the layered result in the debug overlay
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import kconfiglib

_SET_RE = re.compile(r"^CONFIG_([A-Za-z0-9_]+)=(.*)$")
_UNSET_RE = re.compile(r"^# CONFIG_([A-Za-z0-9_]+) is not set$")


@dataclass(frozen=True)
class Assignment:
    path: str
    line: int
    name: str
    value: str


def read_fragment(path: Path) -> list[Assignment]:
    assignments = []
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = raw.strip()
        if match := _SET_RE.match(line):
            value = match.group(2).strip('"')
            assignments.append(Assignment(str(path), number, match.group(1), value))
        elif match := _UNSET_RE.match(line):
            assignments.append(Assignment(str(path), number, match.group(1), "n"))
    return assignments


def load(kconfig: Path, board_kconfig: Path, fragments: list[Path]) -> tuple[kconfiglib.Kconfig, list[str]]:
    """Merge the fragments in order and return the configuration and any errors."""
    os.environ["VK_BOARD_KCONFIG"] = str(board_kconfig)
    kconf = kconfiglib.Kconfig(str(kconfig), warn_to_stderr=False)
    errors = []
    for fragment in fragments:
        if not fragment.exists():
            continue
        kconf.load_config(str(fragment), replace=False)
        for a in read_fragment(fragment):
            sym = kconf.syms.get(a.name)
            if sym is None or not sym.nodes:
                errors.append(f"{a.path}:{a.line}: error: CONFIG_{a.name} is not a known option")
                continue
            if sym.str_value != a.value:
                reason = kconfiglib.expr_str(sym.direct_dep)
                why = f"it depends on {reason}" if reason != "y" else "it has no prompt and is only selected"
                errors.append(f"{a.path}:{a.line}: error: CONFIG_{a.name}={a.value} did not take effect "
                              f"(value is {sym.str_value}): {why}")
    return kconf, errors


def write_outputs(kconf: kconfiglib.Kconfig, out_dir: Path) -> None:
    (out_dir / "vk").mkdir(parents=True, exist_ok=True)
    kconf.write_config(str(out_dir / ".config"), header="# Generated by tools/kconfig/vkconfig.py. Do not edit.\n")
    kconf.write_autoconf(str(out_dir / "vk" / "config.h"),
                         header="/* Generated by tools/kconfig/vkconfig.py. Do not edit. */\n")
    lines = ["# Generated by tools/kconfig/vkconfig.py. Do not edit."]
    for sym in kconf.unique_defined_syms:
        if sym.str_value and sym.str_value != "n":
            lines.append(f'set(CONFIG_{sym.name} "{sym.str_value}")')
    _write_if_changed(out_dir / "kconfig.cmake", "\n".join(lines) + "\n")


def _write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def menuconfig(kconf: kconfiglib.Kconfig, overlay: Path, scratch: Path) -> None:
    import menuconfig as kmenuconfig  # part of kconfiglib

    baseline = {sym.name: sym.str_value for sym in kconf.unique_defined_syms}
    kconf.write_config(str(scratch))
    os.environ["KCONFIG_CONFIG"] = str(scratch)
    kmenuconfig.menuconfig(kconf)
    kconf.load_config(str(scratch))
    changes = [sym for sym in kconf.unique_defined_syms
               if sym.nodes[0].prompt and sym.str_value != baseline[sym.name]]
    lines = ["# Local debug overlay written by menuconfig (ADR-0017). Never committed."]
    for sym in changes:
        lines.append(f"# CONFIG_{sym.name} is not set" if sym.str_value == "n"
                     else f"CONFIG_{sym.name}={sym.str_value}")
    overlay.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Saved {len(changes)} change(s) to {overlay}; the next build reconfigures.")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Solve Vehkernel's layered Kconfig configuration.")
    parser.add_argument("command", choices=("generate", "menuconfig"))
    parser.add_argument("--kconfig", type=Path, required=True, help="root Kconfig file")
    parser.add_argument("--board-kconfig", type=Path, required=True, help="board symbols fragment")
    parser.add_argument("--fragment", type=Path, action="append", default=[],
                        help="configuration fragment, in merge order; may be repeated")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--overlay", type=Path, help="debug overlay that menuconfig writes")
    args = parser.parse_args(argv)

    try:
        kconf, errors = load(args.kconfig, args.board_kconfig, args.fragment)
    except kconfiglib.KconfigError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if args.command == "generate":
        write_outputs(kconf, args.output_dir)
        return 0
    if args.overlay is None:
        parser.error("menuconfig needs --overlay")
    menuconfig(kconf, args.overlay, args.output_dir / ".config.menuconfig")
    return 0


if __name__ == "__main__":
    sys.exit(main())

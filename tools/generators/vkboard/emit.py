"""Emit generator outputs. Identical boards produce byte-identical files."""

from __future__ import annotations

import json
import re

from .board import Board, Function, Pin
from .dma import DmaAssignment

GENERATOR = "tools/generators/generate_board.py"


def _pin_type(p: Pin, f: Function) -> str:
    port = f"vk::hal::Port::{p.port}"
    if f.kind == "af":
        return f'vk::hal::AfPin<{port}, {p.number}, {f.af}, "{f.func}">'
    if f.kind == "analog":
        return f'vk::hal::AnalogPin<{port}, {p.number}, "{f.func}">'
    if f.kind == "gpio_input":
        return f"vk::hal::GpioInput<{port}, {p.number}>"
    return f"vk::hal::GpioOutput<{port}, {p.number}>"


def board_header(board: Board) -> str:
    out = [
        f"// Generated by {GENERATOR} from {board.source}. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "#include <vk/hal/dma.hpp>",
        "#include <vk/hal/pin.hpp>",
        "#include <vk/hal/rotation.hpp>",
        "#include <vk/hal/timing.hpp>",
        "",
        "namespace vk::board {",
        "",
        f'inline constexpr std::string_view name = "{board.name}";',
        f'inline constexpr std::string_view mcu = "{board.mcu}";',
        "",
        "namespace pins {",
    ]
    for p in board.pins:
        out.append(f"using {p.role} = {_pin_type(p, p.default)};  // {p.pin} {p.func}")
    out.append("")
    roles = ", ".join(p.role for p in board.pins)
    out.append(f"using all = vk::hal::PinList<{roles}>;")
    for config in board.alt_configs:
        out += ["", f"// Alt config {config}: the pins whose role changes when it is selected at boot.",
                f"namespace alt{config} {{"]
        for p in board.pins:
            f = p.in_config(config)
            if f != p.default:
                out.append(f"using {f.role} = {_pin_type(p, f)};  // {p.pin} {f.func}")
        effective = ", ".join(
            (f"alt{config}::{p.in_config(config).role}" if p.in_config(config) != p.default else p.role)
            for p in board.pins)
        out.append(f"using all = vk::hal::PinList<{effective}>;")
        out.append(f"}}  // namespace alt{config}")
    out += ["}  // namespace pins", ""]
    if board.alt_configs:
        configs = ", ".join(str(c) for c in board.alt_configs)
        out += [f"// Alt configs selectable at boot besides the default (0): {configs}.",
                f"inline constexpr unsigned alt_config_count = {len(board.alt_configs)};", ""]
    out += _dma_namespace(board.dma)
    out += _flash_namespace(board)
    out += _clock_namespace(board)
    out += _peripherals_namespace(board)
    out += _ports_namespace(board)
    out += _devices_namespace(board)
    out += _defaults_namespace(board)
    out += ["}  // namespace vk::board", ""]
    return "\n".join(out)


def _dma_namespace(assignments: tuple[DmaAssignment, ...]) -> list[str]:
    out = ["namespace dma {"]
    for a in assignments:
        if a.candidate is None:
            out.append(f"// {a.request}: DMA disabled by the board definition")
            continue
        c = a.candidate
        controller = "Dma1" if c.controller == "DMA1" else "Dma2"
        shared = "true" if a.shared_with else "false"
        out.append(f"using {a.request} = vk::hal::DmaStream<vk::hal::DmaController::{controller}, "
                   f"{c.stream}, {c.channel}, {shared}>;")
    out += ["}  // namespace dma", ""]
    return out


def _flash_namespace(board: Board) -> list[str]:
    if not board.flash:
        return []
    out = ["// Internal Flash layout (ADR-0020); sector numbers are inclusive.", "namespace flash {"]
    for r in board.flash:
        out += [f"struct {r.name} {{",
                f"    static constexpr std::uint32_t address = 0x{r.start:08X};",
                f"    static constexpr std::uint32_t size = {r.size};",
                f"    static constexpr std::uint8_t first_sector = {r.first_sector};",
                f"    static constexpr std::uint8_t last_sector = {r.last_sector};",
                "};"]
    out += ["}  // namespace flash", ""]
    return out


def _camel(name: str) -> str:
    return "".join(w if w.isdigit() else w.capitalize() for w in name.split("_"))


def _clock_namespace(board: Board) -> list[str]:
    c = board.clock
    if c is None:
        return []
    values = [("hse_hz", c.hse_hz), ("sysclk_hz", c.sysclk_hz), ("pll_m", c.pll_m), ("pll_n", c.pll_n),
              ("pll_p", c.pll_p), ("pll_q", c.pll_q), ("apb1_div", c.apb1_div), ("apb2_div", c.apb2_div),
              ("apb1_hz", c.apb1_hz), ("apb2_hz", c.apb2_hz), ("apb1_timer_hz", c.apb1_timer_hz),
              ("apb2_timer_hz", c.apb2_timer_hz), ("flash_wait_states", c.flash_wait_states)]
    out = ["// Clock tree solved from the crystal and target system clock; USB gets exactly 48 MHz.",
           "namespace clock {"]
    out += [f"inline constexpr std::uint32_t {name} = {value};" for name, value in values]
    return out + ["}  // namespace clock", ""]


def _peripherals_namespace(board: Board) -> list[str]:
    if not board.peripherals:
        return []
    # Lower case: the CMSIS device headers define the upper-case names (TIM3,
    # USART1, ...) as macros, which would break any file including both.
    out = ["// Peripheral instances the board uses, named in lower case because CMSIS",
           "// defines the upper-case names as macros.",
           "namespace peripherals {"]
    for name, info in board.peripherals:
        bus = f'"{info["bus_clock"]}"' if info["bus_clock"] else '""'
        out += [f"struct {name.lower()} {{",
                f"    static constexpr std::uint32_t address = 0x{info['address']:08X};",
                f'    static constexpr std::string_view kind = "{info["kind"]}";',
                f"    static constexpr std::string_view bus_clock = {bus};",
                "};"]
    return out + ["}  // namespace peripherals", ""]


def _ports_namespace(board: Board) -> list[str]:
    ports = board.hardware.serial
    if not ports:
        return []
    solved = {a.request for a in board.dma if a.candidate is not None}
    instances = {name for name, _ in board.peripherals}
    out = ["// Logical serial ports; SERIALn_FUNCTION picks their use at runtime.", "namespace ports {"]
    for p in ports:
        out.append(f"struct {p.port} {{")
        out.append(f'    static constexpr std::string_view peripheral = "{p.peripheral}";')
        if p.peripheral in instances:
            out.append(f"    using registers = peripherals::{p.peripheral.lower()};")
        for direction in ("tx", "rx"):
            if getattr(p, direction):
                out.append(f"    using {direction} = pins::{getattr(p, direction)};")
                if f"{p.peripheral}_{direction.upper()}" in solved:
                    out.append(f"    using {direction}_dma = dma::{p.peripheral}_{direction.upper()};")
        out.append("};")
    return out + ["}  // namespace ports", ""]


def _devices_namespace(board: Board) -> list[str]:
    devices = board.hardware.devices
    if not devices:
        return []
    out = ["namespace devices {"]
    for d in devices:
        out += [f"struct {d.device} {{",
                f'    static constexpr std::string_view kind = "{d.kind}";',
                f'    static constexpr std::string_view type = "{d.type}";',
                f'    static constexpr std::string_view bus = "{d.bus}";']
        if d.peripheral:
            out.append(f'    static constexpr std::string_view peripheral = "{d.peripheral}";')
        if d.address is not None:
            out.append(f"    static constexpr std::uint8_t address = 0x{d.address:02X};")
        out.append(f"    static constexpr vk::hal::Rotation rotation = vk::hal::Rotation::{_camel(d.rotation)};")
        out.append(f"    using pins = vk::hal::PinList<{', '.join(f'pins::{r}' for r in d.pins)}>;")
        out.append("};")
    return out + ["}  // namespace devices", ""]


def _default_constant(name: str, value: object) -> str:
    if isinstance(value, bool):
        return f"inline constexpr bool {name} = {'true' if value else 'false'};"
    if isinstance(value, int):
        return f"inline constexpr std::int32_t {name} = {value};"
    if isinstance(value, float):
        return f"inline constexpr float {name} = {value!r}F;"
    return f'inline constexpr std::string_view {name} = "{value}";'


def _defaults_namespace(board: Board) -> list[str]:
    """Board defaults as constants, usable before the parameter system exists (ADR-0012)."""
    params = dict(board.hardware.defaults)
    if not params:
        return []
    out = ["// Board default parameters (ADR-0012), as compile-time constants until the",
           "// parameter system exists.",
           "namespace defaults {"]
    out += [_default_constant(name, value) for name, value in board.hardware.defaults]
    out += ["}  // namespace defaults", ""]
    timing = []
    if "CTRL_TRIGGER" in params:
        timing.append("inline constexpr vk::hal::TimingTrigger trigger = "
                      f"vk::hal::TimingTrigger::{_camel(params['CTRL_TRIGGER'])};")
    if "CTRL_RATE_HZ" in params:
        timing.append(f"inline constexpr std::uint32_t base_rate_hz = {params['CTRL_RATE_HZ']};")
    if "IMU_SAMPLING" in params:
        timing.append("inline constexpr vk::hal::ImuSampling sampling = "
                      f"vk::hal::ImuSampling::{_camel(params['IMU_SAMPLING'])};")
    if timing:
        out += ["// Timing preset (ADR-0015), typed.", "namespace timing {", *timing,
                "}  // namespace timing", ""]
    return out


def board_defaults_json(board: Board) -> str:
    return json.dumps(dict(board.hardware.defaults), indent=2) + "\n"


def _size(size: int) -> str:
    return f"{size // 1024}K" if size % 1024 == 0 else str(size)


def memory_ld(board: Board) -> str:
    access = {"BOOT": "rx", "FIRMWARE": "rx", "PARAMS": "r", "EVENTLOG": "r", "RAM": "rwx", "CCM": "rw"}
    regions = [(r.name, r.start, r.size) for r in board.flash] + [(r.name, r.start, r.size) for r in board.ram]
    width = max(len(name) for name, _, _ in regions)
    out = [f"/* Generated by {GENERATOR} from {board.source}. Do not edit. */",
           "/* Region sizes are the size budgets the linker enforces (ADR-0017, ADR-0020). */",
           "MEMORY", "{"]
    for name, start, size in regions:
        out.append(f"    {name.ljust(width)} ({access[name]}){' ' * (3 - len(access[name]))} : "
                   f"ORIGIN = 0x{start:08X}, LENGTH = {_size(size)}")
    out += ["}", ""]
    for r in board.flash:
        out.append(f"__vk_flash_{r.name.lower()}_start = ORIGIN({r.name});")
        out.append(f"__vk_flash_{r.name.lower()}_end = ORIGIN({r.name}) + LENGTH({r.name});")
    return "\n".join(out) + "\n"


def board_symbols(board: Board) -> list[str]:
    """Hardware facts as Kconfig symbol names, sorted (ADR-0017)."""
    symbols = set()
    for p in board.pins:
        for f in (p.default, *(fn for _, fn in p.alt)):
            if f.kind in ("af", "analog"):
                instance = f.func.rsplit("_", 1)[0]
                symbols.add(f"BOARD_HAS_{instance}")
                symbols.add(f"BOARD_HAS_{re.sub(r'[0-9]+$', '', instance)}")
    for r in board.flash:
        if r.name in ("PARAMS", "EVENTLOG"):
            symbols.add(f"BOARD_HAS_FLASH_{r.name}")
    for d in board.hardware.devices:
        symbols.add(f"BOARD_HAS_{d.type}")
        symbols.add(f"BOARD_{d.kind}_BUS_{d.bus}")
    for s in board.hardware.storage:
        symbols.add(f"BOARD_HAS_{s.storage}")
    # A serial port with both lines whose default use is a Link (spec 0003).
    if any(p.function == "LINK" and p.tx and p.rx for p in board.hardware.serial):
        symbols.add("BOARD_HAS_LINK_PORT")
    return sorted(symbols)


def kconfig_board(board: Board) -> str:
    out = [f"# Generated by {GENERATOR} from {board.source}. Do not edit.",
           f"# Hardware facts of board {board.name}, for options to depend on (ADR-0017)."]
    for symbol in board_symbols(board):
        out += ["", f"config {symbol}", "\tbool", "\tdefault y"]
    return "\n".join(out) + "\n"


def dma_report(board: Board) -> str:
    rows = [("request", "stream", "channel", "priority", "notes", "candidates")]
    for a in board.dma:
        candidates = ", ".join(map(str, a.candidates))
        if a.candidate is None:
            rows.append((a.request, "-", "-", str(a.priority), "DMA disabled", candidates))
            continue
        notes = []
        if a.shared_with:
            notes.append("shared with " + ", ".join(a.shared_with))
        elif a.share:
            notes.append("sharing allowed")
        rows.append((a.request, f"{a.candidate.controller} S{a.candidate.stream}", str(a.candidate.channel),
                     str(a.priority), "; ".join(notes) or "-", candidates))
    widths = [max(len(row[i]) for row in rows) for i in range(len(rows[0]) - 1)]
    lines = [f"DMA assignment for board {board.name}, generated from {board.source}.", ""]
    for row in rows:
        cells = [cell.ljust(width) for cell, width in zip(row, widths)] + [row[-1]]
        lines.append("  ".join(cells).rstrip())
    if len(rows) == 1:
        lines.append("(no DMA requests)")
    return "\n".join(lines) + "\n"


def board_json(board: Board) -> str:
    data = {
        "name": board.name,
        "mcu": board.mcu,
        "pins": [
            {"role": p.role, "pin": p.pin, "port": p.port, "number": p.number,
             "func": p.func, "kind": p.kind, "af": p.af,
             "alt": [{"config": config, "role": f.role, "func": f.func, "kind": f.kind, "af": f.af}
                     for config, f in p.alt]}
            for p in board.pins
        ],
        "alt_configs": list(board.alt_configs),
        "flash": [{"region": r.name, "start": r.start, "size": r.size,
                   "first_sector": r.first_sector, "last_sector": r.last_sector} for r in board.flash],
        "ram": [{"region": r.name, "start": r.start, "size": r.size} for r in board.ram],
        "serial": [{"port": p.port, "peripheral": p.peripheral, "tx": p.tx, "rx": p.rx, "function": p.function}
                   for p in board.hardware.serial],
        "devices": [{"device": d.device, "kind": d.kind, "type": d.type, "bus": d.bus,
                     "peripheral": d.peripheral, "pins": list(d.pins), "address": d.address,
                     "rotation": d.rotation} for d in board.hardware.devices],
        "storage": [{"storage": s.storage, "bus": s.bus} for s in board.hardware.storage],
        "clock": None if board.clock is None else {
            "hse_hz": board.clock.hse_hz, "sysclk_hz": board.clock.sysclk_hz, "pll_m": board.clock.pll_m,
            "pll_n": board.clock.pll_n, "pll_p": board.clock.pll_p, "pll_q": board.clock.pll_q,
            "apb1_div": board.clock.apb1_div, "apb2_div": board.clock.apb2_div,
            "flash_wait_states": board.clock.flash_wait_states},
        "peripherals": [{"name": name, **info} for name, info in board.peripherals],
        "dma": [
            {"request": a.request,
             "controller": a.candidate.controller if a.candidate else None,
             "stream": a.candidate.stream if a.candidate else None,
             "channel": a.candidate.channel if a.candidate else None,
             "priority": a.priority, "share": a.share, "shared_with": list(a.shared_with)}
            for a in board.dma
        ],
    }
    return json.dumps(data, indent=2) + "\n"


def outputs(board: Board) -> dict[str, str]:
    """Map of output file name to contents."""
    files = {"board.hpp": board_header(board), "board.json": board_json(board),
             "dma_report.txt": dma_report(board), "Kconfig.board": kconfig_board(board),
             "board_defaults.json": board_defaults_json(board)}
    if board.flash:
        files["memory.ld"] = memory_ld(board)
    return files

"""Emit generator outputs. Identical boards produce byte-identical files."""

from __future__ import annotations

import json
import re

from .board import Board, Function, Pin
from .dma import DmaAssignment

GENERATOR = "tools/generators/generate_board.py"


def _pin_type(p: Pin, f: Function) -> str:
    port = f"vk::hal::Port::{p.port}"
    if f.kind == "af":
        return f'vk::hal::AfPin<{port}, {p.number}, {f.af}, "{f.func}">'
    if f.kind == "analog":
        return f'vk::hal::AnalogPin<{port}, {p.number}, "{f.func}">'
    if f.kind == "gpio_input":
        return f"vk::hal::GpioInput<{port}, {p.number}>"
    return f"vk::hal::GpioOutput<{port}, {p.number}>"


def board_header(board: Board) -> str:
    out = [
        f"// Generated by {GENERATOR} from {board.source}. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "#include <vk/hal/dma.hpp>",
        "#include <vk/hal/pin.hpp>",
        "",
        "namespace vk::board {",
        "",
        f'inline constexpr std::string_view name = "{board.name}";',
        f'inline constexpr std::string_view mcu = "{board.mcu}";',
        "",
        "namespace pins {",
    ]
    for p in board.pins:
        out.append(f"using {p.role} = {_pin_type(p, p.default)};  // {p.pin} {p.func}")
    out.append("")
    roles = ", ".join(p.role for p in board.pins)
    out.append(f"using all = vk::hal::PinList<{roles}>;")
    for config in board.alt_configs:
        out += ["", f"// Alt config {config}: the pins whose role changes when it is selected at boot.",
                f"namespace alt{config} {{"]
        for p in board.pins:
            f = p.in_config(config)
            if f != p.default:
                out.append(f"using {f.role} = {_pin_type(p, f)};  // {p.pin} {f.func}")
        effective = ", ".join(
            (f"alt{config}::{p.in_config(config).role}" if p.in_config(config) != p.default else p.role)
            for p in board.pins)
        out.append(f"using all = vk::hal::PinList<{effective}>;")
        out.append(f"}}  // namespace alt{config}")
    out += ["}  // namespace pins", ""]
    if board.alt_configs:
        configs = ", ".join(str(c) for c in board.alt_configs)
        out += [f"// Alt configs selectable at boot besides the default (0): {configs}.",
                f"inline constexpr unsigned alt_config_count = {len(board.alt_configs)};", ""]
    out += _dma_namespace(board.dma)
    out += _flash_namespace(board)
    out += ["}  // namespace vk::board", ""]
    return "\n".join(out)


def _dma_namespace(assignments: tuple[DmaAssignment, ...]) -> list[str]:
    out = ["namespace dma {"]
    for a in assignments:
        if a.candidate is None:
            out.append(f"// {a.request}: DMA disabled by the board definition")
            continue
        c = a.candidate
        controller = "Dma1" if c.controller == "DMA1" else "Dma2"
        shared = "true" if a.shared_with else "false"
        out.append(f"using {a.request} = vk::hal::DmaStream<vk::hal::DmaController::{controller}, "
                   f"{c.stream}, {c.channel}, {shared}>;")
    out += ["}  // namespace dma", ""]
    return out


def _flash_namespace(board: Board) -> list[str]:
    if not board.flash:
        return []
    out = ["// Internal Flash layout (ADR-0020); sector numbers are inclusive.", "namespace flash {"]
    for r in board.flash:
        out += [f"struct {r.name} {{",
                f"    static constexpr std::uint32_t address = 0x{r.start:08X};",
                f"    static constexpr std::uint32_t size = {r.size};",
                f"    static constexpr std::uint8_t first_sector = {r.first_sector};",
                f"    static constexpr std::uint8_t last_sector = {r.last_sector};",
                "};"]
    out += ["}  // namespace flash", ""]
    return out


def _size(size: int) -> str:
    return f"{size // 1024}K" if size % 1024 == 0 else str(size)


def memory_ld(board: Board) -> str:
    access = {"BOOT": "rx", "FIRMWARE": "rx", "PARAMS": "r", "EVENTLOG": "r", "RAM": "rwx", "CCM": "rw"}
    regions = [(r.name, r.start, r.size) for r in board.flash] + [(r.name, r.start, r.size) for r in board.ram]
    width = max(len(name) for name, _, _ in regions)
    out = [f"/* Generated by {GENERATOR} from {board.source}. Do not edit. */",
           "/* Region sizes are the size budgets the linker enforces (ADR-0017, ADR-0020). */",
           "MEMORY", "{"]
    for name, start, size in regions:
        out.append(f"    {name.ljust(width)} ({access[name]}){' ' * (3 - len(access[name]))} : "
                   f"ORIGIN = 0x{start:08X}, LENGTH = {_size(size)}")
    out += ["}", ""]
    for r in board.flash:
        out.append(f"__vk_flash_{r.name.lower()}_start = ORIGIN({r.name});")
        out.append(f"__vk_flash_{r.name.lower()}_end = ORIGIN({r.name}) + LENGTH({r.name});")
    return "\n".join(out) + "\n"


def board_symbols(board: Board) -> list[str]:
    """Hardware facts as Kconfig symbol names, sorted (ADR-0017)."""
    symbols = set()
    for p in board.pins:
        for f in (p.default, *(fn for _, fn in p.alt)):
            if f.kind in ("af", "analog"):
                instance = f.func.rsplit("_", 1)[0]
                symbols.add(f"BOARD_HAS_{instance}")
                symbols.add(f"BOARD_HAS_{re.sub(r'[0-9]+$', '', instance)}")
    for r in board.flash:
        if r.name in ("PARAMS", "EVENTLOG"):
            symbols.add(f"BOARD_HAS_FLASH_{r.name}")
    return sorted(symbols)


def kconfig_board(board: Board) -> str:
    out = [f"# Generated by {GENERATOR} from {board.source}. Do not edit.",
           f"# Hardware facts of board {board.name}, for options to depend on (ADR-0017)."]
    for symbol in board_symbols(board):
        out += ["", f"config {symbol}", "\tbool", "\tdefault y"]
    return "\n".join(out) + "\n"


def dma_report(board: Board) -> str:
    rows = [("request", "stream", "channel", "priority", "notes", "candidates")]
    for a in board.dma:
        candidates = ", ".join(map(str, a.candidates))
        if a.candidate is None:
            rows.append((a.request, "-", "-", str(a.priority), "DMA disabled", candidates))
            continue
        notes = []
        if a.shared_with:
            notes.append("shared with " + ", ".join(a.shared_with))
        elif a.share:
            notes.append("sharing allowed")
        rows.append((a.request, f"{a.candidate.controller} S{a.candidate.stream}", str(a.candidate.channel),
                     str(a.priority), "; ".join(notes) or "-", candidates))
    widths = [max(len(row[i]) for row in rows) for i in range(len(rows[0]) - 1)]
    lines = [f"DMA assignment for board {board.name}, generated from {board.source}.", ""]
    for row in rows:
        cells = [cell.ljust(width) for cell, width in zip(row, widths)] + [row[-1]]
        lines.append("  ".join(cells).rstrip())
    if len(rows) == 1:
        lines.append("(no DMA requests)")
    return "\n".join(lines) + "\n"


def board_json(board: Board) -> str:
    data = {
        "name": board.name,
        "mcu": board.mcu,
        "pins": [
            {"role": p.role, "pin": p.pin, "port": p.port, "number": p.number,
             "func": p.func, "kind": p.kind, "af": p.af,
             "alt": [{"config": config, "role": f.role, "func": f.func, "kind": f.kind, "af": f.af}
                     for config, f in p.alt]}
            for p in board.pins
        ],
        "alt_configs": list(board.alt_configs),
        "flash": [{"region": r.name, "start": r.start, "size": r.size,
                   "first_sector": r.first_sector, "last_sector": r.last_sector} for r in board.flash],
        "ram": [{"region": r.name, "start": r.start, "size": r.size} for r in board.ram],
        "dma": [
            {"request": a.request,
             "controller": a.candidate.controller if a.candidate else None,
             "stream": a.candidate.stream if a.candidate else None,
             "channel": a.candidate.channel if a.candidate else None,
             "priority": a.priority, "share": a.share, "shared_with": list(a.shared_with)}
            for a in board.dma
        ],
    }
    return json.dumps(data, indent=2) + "\n"


def outputs(board: Board) -> dict[str, str]:
    """Map of output file name to contents."""
    files = {"board.hpp": board_header(board), "board.json": board_json(board),
             "dma_report.txt": dma_report(board), "Kconfig.board": kconfig_board(board)}
    if board.flash:
        files["memory.ld"] = memory_ld(board)
    return files

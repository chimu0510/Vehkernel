"""Emit generator outputs. Identical definitions produce byte-identical files."""

from __future__ import annotations

import json

from .params import Group, Param, all_params, metadata, set_hash

GENERATOR = "tools/generators/generate_params.py"


def _literal(param: Param, value: int | float) -> str:
    if param.type == "FLOAT":
        return f"{float(value)!r}F"
    return str(int(value))


def _value(param: Param, value: int | float) -> str:
    kind = "from_float" if param.type == "FLOAT" else "from_int"
    return f"core::ParamValue::{kind}({_literal(param, value)})"


def _comment(param: Param) -> str:
    notes = [param.name]
    if param.unit:
        notes.append(f"[{param.unit}]")
    notes.append(param.description)
    return " ".join(notes)


def _values_array(param: Param) -> str:
    return f"{param.name.lower()}_values"


def _names_array(param: Param) -> str:
    return f"{param.name.lower()}_names"


def params_header(groups: list[Group], params: list[Param]) -> str:
    out = [
        f"// Generated by {GENERATOR}. Do not edit.",
        "// Parameter groups (ADR-0012): plain structs in RAM that modules read",
        "// directly. Changes go through vk::params::parameters(), which publishes",
        "// parameter_update.",
        "#pragma once",
        "",
        "#include <vk/core/parameters.hpp>",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <span>",
        "",
        "namespace vk::params {",
        "",
    ]
    for group in groups:
        out.append(f"// From {group.source}.")
        out += [f"// {line}" if line else "//" for line in group.doc]
        out.append(f"struct {group.type_name} {{")
        for param in group.params:
            cpp_type = "float" if param.type == "FLOAT" else "std::int32_t"
            out.append(f"    {cpp_type} {param.member} = {_literal(param, param.default)};  // {_comment(param)}")
        out += ["};", f"extern {group.type_name} {group.instance};", ""]
    out += [
        "// Every compiled-in parameter, sorted by name.",
        f"inline constexpr std::size_t count = {len(params)};",
        "// First 64 bits of SHA-256 over the metadata file's parameters (ADR-0012).",
        f"inline constexpr std::uint64_t set_hash = 0x{set_hash(params):016X}ULL;",
        "",
        "// The parameter table, sorted by name.",
        "std::span<const core::ParamInfo> table();",
        "",
        "// The build's parameter runtime over table().",
        "core::Parameters& parameters();",
        "",
        "// The parameters in the local menu, in table order (ADR-0022).",
        "std::span<const core::MenuParam> menu();",
        "",
        "}  // namespace vk::params",
        "",
    ]
    return "\n".join(out)


def params_source(groups: list[Group], params: list[Param]) -> str:
    out = [
        f"// Generated by {GENERATOR}. Do not edit.",
        "#include <vk/params/params.hpp>",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace vk::params {",
        "",
    ]
    if groups:
        out += [f"{g.type_name} {g.instance}{{}};" for g in groups] + [""]
    out += ["namespace {", ""]
    for param in params:
        if param.is_enum:
            values = ", ".join(str(v.value) for v in param.values)
            out.append(f"constexpr std::array<std::int32_t, {len(param.values)}> {_values_array(param)}{{{values}}};")
    if any(p.is_enum for p in params):
        out.append("")
    menu = [(index, p) for index, p in enumerate(params) if p.menu]
    # Enum value names only for menu parameters; every other parameter keeps
    # only what validation needs (ADR-0012).
    for _, param in menu:
        if param.is_enum:
            names = ", ".join(f'"{v.name}"' for v in param.values)
            out.append(f"constexpr std::array<std::string_view, {len(param.values)}> {_names_array(param)}{{{names}}};")
    if any(p.is_enum for _, p in menu):
        out.append("")
    group_of = {p.name: g for g in groups for p in g.params}
    out.append(f"constinit const std::array<core::ParamInfo, {len(params)}> entries{{{{")
    for param in params:
        flags = []
        if param.reboot_required:
            flags.append("core::param_flags::reboot_required")
        if param.locked_when_armed:
            flags.append("core::param_flags::locked_when_armed")
        group = group_of[param.name]
        target = f"&{group.instance}.{param.member}"
        out += [
            "    {",
            f'        .name = "{param.name}",',
            f"        .hash = 0x{param.hash:08X}U,",
            f"        .type = core::ParamType::{'Float' if param.type == 'FLOAT' else 'Int32'},",
            f"        .flags = {' | '.join(flags) if flags else '0'},",
            f"        .default_value = {_value(param, param.default)},",
            f"        .min = {_value(param, param.minimum)},",
            f"        .max = {_value(param, param.maximum)},",
            f"        .enum_values = {_values_array(param) if param.is_enum else '{}'},",
            f"        .bitmask = 0x{sum(1 << b.bit for b in param.bits):08X}U,",
            f"        .int_value = {'nullptr' if param.type == 'FLOAT' else target},",
            f"        .float_value = {target if param.type == 'FLOAT' else 'nullptr'},",
            "    },",
        ]
    out += ["}};", ""]
    out.append(f"constinit const std::array<core::MenuParam, {len(menu)}> menu_entries{{{{")
    for index, param in menu:
        step = _value(param, param.menu_step) if param.menu_step is not None else "{}"
        names = _names_array(param) if param.is_enum else "{}"
        out.append(f"    {{.index = {index}, .step = {step}, .value_names = {names}}},  // {param.name}")
    out += [
        "}};",
        "",
        "}  // namespace",
        "",
        "std::span<const core::ParamInfo> table()",
        "{",
        "    return entries;",
        "}",
        "",
        "core::Parameters& parameters()",
        "{",
        "    static core::Parameters instance(entries);",
        "    return instance;",
        "}",
        "",
        "std::span<const core::MenuParam> menu()",
        "{",
        "    return menu_entries;",
        "}",
        "",
        "}  // namespace vk::params",
        "",
    ]
    return "\n".join(out)


def metadata_file(params: list[Param]) -> str:
    document = {
        "generator": GENERATOR,
        "set_hash": f"0x{set_hash(params):016X}",
        "parameters": [metadata(p) for p in params],
    }
    return json.dumps(document, indent=2) + "\n"


def outputs(groups: list[Group]) -> dict[str, str]:
    """Generated files keyed by their path relative to the output directory."""
    params = all_params(groups)
    return {
        "vk/params/params.hpp": params_header(groups, params),
        "vk/params/params.cpp": params_source(groups, params),
        "params.json": metadata_file(params),
    }

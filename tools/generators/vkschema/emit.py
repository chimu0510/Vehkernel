"""Emit generator outputs. Identical schemas produce byte-identical files."""

from __future__ import annotations

import textwrap

from .schema import Enum, Message, Schema, type_name

GENERATOR = "tools/generators/generate_schema.py"


def _float_literal(value: float) -> str:
    text = repr(float(value))
    return f"{text}F"


def message_header(message: Message, topic_id: int) -> str:
    names = ", ".join(f.name for f in message.fields)
    out = [
        f"// Generated by {GENERATOR} from {message.source}. Do not edit.",
        "#pragma once",
        "",
        "#include <vk/msg/wire.hpp>",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <span>",
        "#include <string_view>",
        "#include <tuple>",
        "",
        "namespace vk::msg {",
        "",
    ]
    out += [f"// {line}" for line in message.doc]
    out.append(f"struct {message.type_name} {{")
    for f in message.fields:
        notes = []
        if f.unit:
            notes.append(f"[{f.unit}]")
        if f.enum:
            notes.append(f"({type_name(f.enum)})")
        if f.comment:
            notes.append(f.comment)
        suffix = f"  // {' '.join(notes)}" if notes else ""
        out.append(f"    {f.cpp_type} {f.name}{{}};{suffix}")
    out += [
        "",
        f'    static constexpr std::string_view topic_name = "{message.name}";',
        f"    static constexpr std::uint64_t schema_hash = 0x{message.schema_hash:016X}ULL;",
        "    // Position in the sorted schema; Link peers learn it at the handshake.",
        f"    static constexpr std::uint16_t topic_id = {topic_id};",
        "    // 1 keeps only the latest value; more turns the topic into a queue (ADR-0008).",
        f"    static constexpr std::size_t queue_length = {message.queue};",
        f"    static constexpr std::size_t instances = {message.instances};",
        "    // Nominal publish rate; 0 when the schema declares none.",
        f"    static constexpr float nominal_rate_hz = {_float_literal(message.rate_hz)};",
        "    // Bytes on the wire: fields in schema order, packed little-endian (ADR-0006).",
        f"    static constexpr std::size_t encoded_size = {message.encoded_size};",
        "",
        "    // Writes the message to `out`; returns the bytes written, 0 if `out` is too small.",
        "    [[nodiscard]] std::size_t encode(std::span<std::uint8_t> out) const",
        "    {",
        "        if (out.size() < encoded_size) {",
        "            return 0;",
        "        }",
        "        std::size_t at = 0;",
    ]
    out += [f"        wire::put(out, at, {f.name});" for f in message.fields]
    out += [
        "        return at;",
        "    }",
        "",
        "    // Reads a message from exactly encoded_size bytes; false on any other size.",
        f"    [[nodiscard]] static bool decode(std::span<const std::uint8_t> in, {message.type_name}& out)",
        "    {",
        "        if (in.size() != encoded_size) {",
        "            return false;",
        "        }",
        "        std::size_t at = 0;",
    ]
    out += [f"        wire::get(in, at, out.{f.name});" for f in message.fields]
    out += [
        "        return true;",
        "    }",
        "",
        "    // Every field in schema order, for code that handles any message.",
        f"    [[nodiscard]] auto fields() {{ return std::tie({names}); }}",
        f"    [[nodiscard]] auto fields() const {{ return std::tie({names}); }}",
        "};",
        "",
        "}  // namespace vk::msg",
        "",
    ]
    return "\n".join(out)


def wire_header() -> str:
    return "\n".join([
        f"// Generated by {GENERATOR}. Do not edit.",
        "// Packed little-endian encoding of message fields (ADR-0006): each value is",
        "// written byte by byte, never memcpy'd, so the wire format does not depend",
        "// on the compiler or the platform.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <bit>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <span>",
        "#include <type_traits>",
        "",
        "namespace vk::msg::wire {",
        "",
        "template <std::size_t Size>",
        "struct Bits;",
        "template <>",
        "struct Bits<1> {",
        "    using type = std::uint8_t;",
        "};",
        "template <>",
        "struct Bits<2> {",
        "    using type = std::uint16_t;",
        "};",
        "template <>",
        "struct Bits<4> {",
        "    using type = std::uint32_t;",
        "};",
        "template <>",
        "struct Bits<8> {",
        "    using type = std::uint64_t;",
        "};",
        "",
        "template <class T>",
        "    requires std::is_arithmetic_v<T>",
        "inline void put(std::span<std::uint8_t> out, std::size_t& at, T value)",
        "{",
        "    if constexpr (std::is_same_v<T, bool>) {",
        "        out[at++] = value ? 1 : 0;",
        "    } else {",
        "        const auto bits = std::bit_cast<typename Bits<sizeof(T)>::type>(value);",
        "        for (std::size_t i = 0; i < sizeof(T); ++i) {",
        "            out[at++] = static_cast<std::uint8_t>(bits >> (8U * i));",
        "        }",
        "    }",
        "}",
        "",
        "template <class T, std::size_t N>",
        "inline void put(std::span<std::uint8_t> out, std::size_t& at, const std::array<T, N>& values)",
        "{",
        "    for (const T& value : values) {",
        "        put(out, at, value);",
        "    }",
        "}",
        "",
        "template <class T>",
        "    requires std::is_arithmetic_v<T>",
        "inline void get(std::span<const std::uint8_t> in, std::size_t& at, T& value)",
        "{",
        "    if constexpr (std::is_same_v<T, bool>) {",
        "        value = in[at++] != 0;",
        "    } else {",
        "        using U = typename Bits<sizeof(T)>::type;",
        "        U bits = 0;",
        "        for (std::size_t i = 0; i < sizeof(T); ++i) {",
        "            bits = static_cast<U>(bits | (static_cast<U>(in[at++]) << (8U * i)));",
        "        }",
        "        value = std::bit_cast<T>(bits);",
        "    }",
        "}",
        "",
        "template <class T, std::size_t N>",
        "inline void get(std::span<const std::uint8_t> in, std::size_t& at, std::array<T, N>& values)",
        "{",
        "    for (T& value : values) {",
        "        get(in, at, value);",
        "    }",
        "}",
        "",
        "}  // namespace vk::msg::wire",
        "",
    ])


def topics_header(messages: list[Message]) -> str:
    out = [f"// Generated by {GENERATOR}. Do not edit.", "#pragma once", ""]
    out += [f"#include <vk/msg/{m.name}.hpp>" for m in messages]
    out += [
        "",
        "#include <cstddef>",
        "",
        "namespace vk::msg {",
        "",
        "template <class... Messages>",
        "struct TopicList {",
        "    static constexpr std::size_t size = sizeof...(Messages);",
        "};",
        "",
        "// Every message in the schema, in topic ID order.",
        f"using AllTopics = TopicList<{', '.join(m.type_name for m in messages)}>;",
        "",
        "// The largest encoded message.",
        f"inline constexpr std::size_t max_encoded_size = {max((m.encoded_size for m in messages), default=0)};",
        "",
        "}  // namespace vk::msg",
        "",
    ]
    return "\n".join(out)


def _docstring(doc: list[str], fallback: str) -> list[str]:
    """The class docstring lines, wrapped like the rest of the generated code."""
    text = " ".join(doc) if doc else fallback
    text = text.replace("\\", "\\\\").replace('"' * 3, "'" * 3)
    lines = textwrap.wrap(text, width=88)
    if len(lines) == 1:
        return [f'    """{lines[0]}"""']
    return [f'    """{lines[0]}'] + [f"    {line}" for line in lines[1:]] + ['    """']


def python_module(messages: list[Message]) -> str:
    out = [
        f'"""Generated by {GENERATOR}. Do not edit.',
        "",
        "Message types of the schema for tools on the development host, with the",
        "custom protocol's packed little-endian encoding (ADR-0006).",
        '"""',
        "",
        "import struct",
        "",
        "",
    ]
    for topic_id, m in enumerate(messages):
        fmt = "<" + "".join(f.struct_code for f in m.fields)
        args = ", ".join(f"{f.name}={'0' if f.length is None else repr(tuple([0] * f.count))}"
                         if f.type != "bool" else
                         f"{f.name}={'False' if f.length is None else repr(tuple([False] * f.count))}"
                         for f in m.fields)
        out += [
            f"class {m.type_name}:",
            *_docstring(m.doc, f"The {m.name} topic."),
            "",
            f'    NAME = "{m.name}"',
            f"    TOPIC_ID = {topic_id}",
            f"    SCHEMA_HASH = 0x{m.schema_hash:016X}",
            f"    ENCODED_SIZE = {m.encoded_size}",
            f"    QUEUE_LENGTH = {m.queue}",
            f"    INSTANCES = {m.instances}",
            f"    FIELDS = ({', '.join(repr(f.name) for f in m.fields)},)",
            f"    UNITS = {{{', '.join(f'{f.name!r}: {f.unit!r}' for f in m.fields if f.unit)}}}",
            f"    _STRUCT = struct.Struct({fmt!r})",
            "    __slots__ = FIELDS",
            "",
            f"    def __init__(self, {args}):",
        ]
        out += [f"        self.{f.name} = {f.name}" for f in m.fields]
        out += [
            "",
            "    def encode(self) -> bytes:",
            "        return self._STRUCT.pack(",
        ]
        for f in m.fields:
            out.append(f"            self.{f.name}," if f.length is None else f"            *self.{f.name},")
        out += [
            "        )",
            "",
            "    @classmethod",
            f'    def decode(cls, data: bytes) -> "{m.type_name}":',
            "        values = cls._STRUCT.unpack(data)",
            "        return cls(",
        ]
        at = 0
        for f in m.fields:
            if f.length is None:
                out.append(f"            {f.name}=values[{at}],")
            else:
                out.append(f"            {f.name}=tuple(values[{at}:{at + f.count}]),")
            at += f.count
        out += [
            "        )",
            "",
            "    def as_dict(self) -> dict:",
            "        return {name: getattr(self, name) for name in self.FIELDS}",
            "",
            "    def __eq__(self, other) -> bool:",
            "        return type(other) is type(self) and self.as_dict() == other.as_dict()",
            "",
            "    def __repr__(self) -> str:",
            '        return f"{type(self).__name__}({self.as_dict()})"',
            "",
            "",
        ]
    out += [
        "# Every message type, by topic ID and by name.",
        f"TOPICS = {{{', '.join(f'{m.type_name}.TOPIC_ID: {m.type_name}' for m in messages)}}}",
        "BY_NAME = {cls.NAME: cls for cls in TOPICS.values()}",
        "",
    ]
    return "\n".join(out)


def _cpp_string(text: str) -> str:
    return '"' + text + '"'


def enums_header(enums: list[Enum]) -> str:
    out = [
        f"// Generated by {GENERATOR}. Do not edit.",
        "// The enums of the schema (ADR-0006), each with a constexpr table of its",
        "// values. Message fields that take an enum's values keep their integer type,",
        "// so a value the schema does not name still decodes.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace vk::msg {",
        "",
        "// One value of an enum, with its name in the schema and a short name for",
        "// narrow screens such as the local display (ADR-0022), the name itself",
        "// unless the schema gives one.",
        "template <class Enum>",
        "struct EnumValue {",
        "    Enum value;",
        "    std::string_view name;",
        "    std::string_view short_name;",
        "};",
        "",
        "// Every value of an enum in schema order, as `values`; specialized for each enum.",
        "template <class Enum>",
        "struct EnumValues;",
        "",
        "// The name of `value` in the schema, empty for a value the schema does not name.",
        "template <class Enum>",
        "[[nodiscard]] constexpr std::string_view enum_name(Enum value)",
        "{",
        "    for (const auto& entry : EnumValues<Enum>::values) {",
        "        if (entry.value == value) {",
        "            return entry.name;",
        "        }",
        "    }",
        "    return {};",
        "}",
        "",
        "// The short name of `value`, empty for a value the schema does not name.",
        "template <class Enum>",
        "[[nodiscard]] constexpr std::string_view enum_short_name(Enum value)",
        "{",
        "    for (const auto& entry : EnumValues<Enum>::values) {",
        "        if (entry.value == value) {",
        "            return entry.short_name;",
        "        }",
        "    }",
        "    return {};",
        "}",
    ]
    for e in enums:
        out += ["", f"// From {e.source}."]
        out += [f"// {line}" for line in e.doc]
        out.append(f"enum class {e.type_name} : {e.cpp_type} {{")
        out += [f"    {v.cpp_name} = {v.value},{f'  // {v.comment}' if v.comment else ''}" for v in e.values]
        out += [
            "};",
            "",
            "template <>",
            f"struct EnumValues<{e.type_name}> {{",
            f"    static constexpr std::array<EnumValue<{e.type_name}>, {len(e.values)}> values{{{{",
        ]
        out += [f"        {{.value = {e.type_name}::{v.cpp_name}, .name = {_cpp_string(v.name)}, "
                f".short_name = {_cpp_string(v.short_name)}}},"
                for v in e.values]
        out += [
            "    }};",
            "};",
        ]
    out += [
        "",
        "}  // namespace vk::msg",
        "",
    ]
    return "\n".join(out)


def python_enums(enums: list[Enum]) -> str:
    out = [
        f'"""Generated by {GENERATOR}. Do not edit.',
        "",
        "The enums of the schema (ADR-0006) for tools on the development host. The",
        "Link tools keep a copy in tools/link/vklink/enums.py, which the schema",
        "generator tests compare with this file.",
        '"""',
        "",
        "import enum",
        "",
    ]
    for e in enums:
        out += [
            "",
            f"class {e.type_name}(enum.IntEnum):",
            *_docstring(e.doc, f"The {e.name} enum."),
            "",
        ]
        out += [f"    {v.name} = {v.value}{f'  # {v.comment}' if v.comment else ''}" for v in e.values]
        out.append("")
    return "\n".join(out)


def registry_header() -> str:
    return "\n".join([
        f"// Generated by {GENERATOR}. Do not edit.",
        "#pragma once",
        "",
        "#include <span>",
        "",
        "namespace vk::core {",
        "class TopicBase;",
        "}  // namespace vk::core",
        "",
        "namespace vk::msg {",
        "",
        "// Every topic instance in the schema, sorted by topic name, then instance (ADR-0008).",
        "std::span<const vk::core::TopicBase* const> all_topics();",
        "",
        "}  // namespace vk::msg",
        "",
    ])


def registry_source(messages: list[Message]) -> str:
    entries = [f"    &vk::core::topic_instances<{m.type_name}>[{i}],"
               for m in messages for i in range(m.instances)]
    out = [
        f"// Generated by {GENERATOR}. Do not edit.",
        "// The static storage of every topic instance and the list of all of them (ADR-0008).",
        "#include <vk/msg/registry.hpp>",
        "",
        "#include <vk/core/bus.hpp>",
    ]
    out += [f"#include <vk/msg/{m.name}.hpp>" for m in messages]
    out += [
        "",
        "#include <array>",
        "",
        "namespace vk::msg {",
        "namespace {",
        "",
        f"const std::array<const vk::core::TopicBase*, {len(entries)}> topics = {{",
        *entries,
        "};",
        "",
        "}  // namespace",
        "",
        "std::span<const vk::core::TopicBase* const> all_topics()",
        "{",
        "    return topics;",
        "}",
        "",
        "}  // namespace vk::msg",
        "",
    ]
    return "\n".join(out)


def outputs(schema: Schema) -> dict[str, str]:
    """Generated files keyed by their path relative to the output directory."""
    messages = schema.messages
    files = {f"vk/msg/{m.name}.hpp": message_header(m, topic_id) for topic_id, m in enumerate(messages)}
    files["vk/msg/wire.hpp"] = wire_header()
    files["vk/msg/topics.hpp"] = topics_header(messages)
    files["vk/msg/enums.hpp"] = enums_header(schema.enums)
    files["python/vkmsg.py"] = python_module(messages)
    files["python/vkenums.py"] = python_enums(schema.enums)
    files["vk/msg/registry.hpp"] = registry_header()
    files["vk/msg/registry.cpp"] = registry_source(messages)
    return files

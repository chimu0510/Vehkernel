def log_profiles_header(profiles: list[Profile], schema: Schema) -> str:
    msg_ids = {m.name: i for i, m in enumerate(schema.messages)}
    msg_map = {m.name: m for m in schema.messages}

    enum_type = "std::uint8_t" if len(profiles) <= 8 else ("std::uint16_t" if len(profiles) <= 16 else "std::uint32_t")
    out = [
        f"// Generated by {GENERATOR}. Do not edit.",
        "// Log profile tables (spec 0011, ADR-0019).",
        "#pragma once",
        "",
        "#include <vk/config.h>",
        "#include <vk/msg/topics.hpp>",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <span>",
        "#include <string_view>",
        "",
        "namespace vk::msg {",
        "",
        f"enum class LogProfileId : {enum_type} {{",
        "    None = 0,",
    ]
    for i, p in enumerate(profiles):
        out.append(f"    {p.type_name} = 1U << {i},")
    out += [
        "};",
        "",
        "enum class LogRateKind : std::uint8_t {",
        "    EverySample = 0,",
        "    RateHz = 1,",
        "    AsPublished = 2,",
        "};",
        "",
        "struct LogProfileEntry {",
        "    std::uint16_t topic_id;",
        "    std::uint8_t instance;",
        "    LogRateKind rate_kind;",
        "    float rate_hz;",
        "};",
        "",
        "struct LogProfile {",
        "    LogProfileId id;",
        "    std::string_view name;",
        "    std::string_view description;",
        "    float bandwidth;  // bytes/s on the wire with Link framing",
        "    std::span<const LogProfileEntry> entries;",
        "};",
        "",
        "namespace detail {",
        "",
    ]

    for p in profiles:
        bw_sitl = p.bandwidth_sitl(schema)
        bw_c50c = p.bandwidth_c50c(schema)
        out += [
            f"#ifdef CONFIG_PLATFORM_SITL",
            f"inline constexpr float {p.name}_bandwidth = {_float_literal(bw_sitl)};",
            f"#else",
            f"inline constexpr float {p.name}_bandwidth = {_float_literal(bw_c50c)};",
            f"#endif",
            "",
            f"inline constexpr std::array {p.name}_entries = {{",
        ]
        for entry in p.entries:
            msg = msg_map[entry.topic]
            tid = msg_ids[entry.topic]
            instances = [entry.instance] if entry.instance is not None else list(range(msg.instances))
            rate_kind = "LogRateKind::EverySample" if entry.rate == "every_sample" else (
                "LogRateKind::AsPublished" if entry.rate == "as_published" else "LogRateKind::RateHz"
            )
            rate_hz = _float_literal(entry.rate_hz(msg))

            if entry.kconfig:
                out.append(f"#ifdef CONFIG_{entry.kconfig}")
            for inst in instances:
                out.append(f"    LogProfileEntry{{.topic_id = {tid}, .instance = {inst}, "
                           f".rate_kind = {rate_kind}, .rate_hz = {rate_hz}}},")
            if entry.kconfig:
                out.append(f"#endif")
        out += [
            "};",
            "",
            f"inline constexpr LogProfile {p.name}_profile{{",
            f"    .id = LogProfileId::{p.type_name},",
            f"    .name = {_cpp_string(p.name)},",
            f"    .description = {_cpp_string(p.description)},",
            f"    .bandwidth = {p.name}_bandwidth,",
            f"    .entries = {p.name}_entries,",
            "};",
            "",
        ]

    out += [
        "}  // namespace detail",
        "",
        "inline constexpr std::array all_log_profiles = {",
    ]
    for p in profiles:
        out.append(f"    detail::{p.name}_profile,")
    out += [
        "};",
        "",
        "[[nodiscard]] inline constexpr const LogProfile* find_log_profile(LogProfileId id)",
        "{",
        "    for (const auto& profile : all_log_profiles) {",
        "        if (profile.id == id) {",
        "            return &profile;",
        "        }",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "[[nodiscard]] inline constexpr const LogProfile* find_log_profile(std::string_view name)",
        "{",
        "    for (const auto& profile : all_log_profiles) {",
        "        if (profile.name == name) {",
        "            return &profile;",
        "        }",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "}  // namespace vk::msg",
        "",
    ]
    return "\n".join(out)


def log_profile_streams_header(profiles: list[Profile], schema: Schema) -> str:
    msg_map = {m.name: m for m in schema.messages}
    used_topics = set()
    for p in profiles:
        for e in p.entries:
            used_topics.add(e.topic)

    out = [
        f"// Generated by {GENERATOR}. Do not edit.",
        "// Link stream holders for log profiles (spec 0011, ADR-0019).",
        "#pragma once",
        "",
        "#include <vk/config.h>",
        "#include <vk/link/topic_map.hpp>",
    ]
    for topic_name in sorted(used_topics):
        out.append(f"#include <vk/msg/{topic_name}.hpp>")

    out += [
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <span>",
        "",
        "namespace vk::link {",
        "",
    ]

    for p in profiles:
        kconfigs = {e.kconfig for e in p.entries if e.kconfig is not None}
        if "PLATFORM_SITL" in kconfigs:
            count_sitl = sum(e.instance_count(msg_map[e.topic]) for e in p.entries)
            count_c50c = sum(e.instance_count(msg_map[e.topic]) for e in p.entries if e.kconfig is None)
            out += [
                f"#ifdef CONFIG_PLATFORM_SITL",
                f"inline constexpr std::size_t {p.name}_stream_count = {count_sitl};",
                f"#else",
                f"inline constexpr std::size_t {p.name}_stream_count = {count_c50c};",
                f"#endif",
                "",
            ]
        else:
            total_count = sum(e.instance_count(msg_map[e.topic]) for e in p.entries)
            out += [
                f"inline constexpr std::size_t {p.name}_stream_count = {total_count};",
                "",
            ]

        out += [
            f"class {p.type_name}Streams {{",
            "public:",
            f"    {p.type_name}Streams()",
            "    {",
            "        std::size_t idx = 0;",
        ]

        for entry in p.entries:
            msg = msg_map[entry.topic]
            instances = [entry.instance] if entry.instance is not None else list(range(msg.instances))
            if entry.kconfig:
                out.append(f"#ifdef CONFIG_{entry.kconfig}")
            for inst in instances:
                out.append(f"        map_[idx++] = &s_{entry.topic}_{inst}_;")
            if entry.kconfig:
                out.append(f"#endif")

        out += [
            "    }",
            "",
            "    [[nodiscard]] std::span<TopicStream* const> streams() { return map_; }",
            "",
            "private:",
        ]

        for entry in p.entries:
            msg = msg_map[entry.topic]
            instances = [entry.instance] if entry.instance is not None else list(range(msg.instances))
            if entry.rate in ("every_sample", "as_published"):
                rate_expr = "every_sample"
            else:
                rate_expr = f"MaxRate{{{_float_literal(float(entry.rate))}}}"

            if entry.kconfig:
                out.append(f"#ifdef CONFIG_{entry.kconfig}")
            for inst in instances:
                out.append(f"    TopicStreamOf<msg::{msg.type_name}> s_{entry.topic}_{inst}_{{{rate_expr}, {inst}}};")
            if entry.kconfig:
                out.append(f"#endif")

        out += [
            f"    std::array<TopicStream*, {p.name}_stream_count> map_{{}};",
            "};",
            "",
        ]

    out += [
        "}  // namespace vk::link",
        "",
    ]
    return "\n".join(out)


def python_log_profiles(profiles: list[Profile], schema: Schema) -> str:
    msg_ids = {m.name: i for i, m in enumerate(schema.messages)}
    msg_map = {m.name: m for m in schema.messages}

    out = [
        f'"""Generated by {GENERATOR}. Do not edit.',
        "",
        "Log profiles for host tools (spec 0011, ADR-0019).",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "import enum",
        "",
        "",
        "class LogProfileId(enum.IntFlag):",
        "    NONE = 0",
    ]
    for i, p in enumerate(profiles):
        out.append(f"    {p.name.upper()} = 1 << {i}")
    out += [
        "",
        "",
        "class LogRateKind(enum.Enum):",
        '    EVERY_SAMPLE = "every_sample"',
        '    RATE_HZ = "rate_hz"',
        '    AS_PUBLISHED = "as_published"',
        "",
        "",
        "@dataclass(frozen=True)",
        "class LogProfileEntry:",
        "    topic: str",
        "    topic_id: int",
        "    instance: int | None",
        "    rate_kind: LogRateKind",
        "    rate_hz: float",
        "    wire_bytes: int",
        "    instance_count: int",
        "    kconfig: str | None = None",
        "",
        "    @property",
        "    def bandwidth(self) -> float:",
        "        return self.rate_hz * self.wire_bytes * self.instance_count",
        "",
        "",
        "@dataclass(frozen=True)",
        "class LogProfile:",
        "    id: LogProfileId",
        "    name: str",
        "    description: str",
        "    entries: tuple[LogProfileEntry, ...]",
        "    bandwidth_c50c: float",
        "    bandwidth_sitl: float",
        "",
        "    def bandwidth(self, kconfig: set[str] | None = None) -> float:",
        "        active = kconfig if kconfig is not None else set()",
        "        return sum(e.bandwidth for e in self.entries if e.kconfig is None or e.kconfig in active)",
        "",
        "",
        "PROFILES = {",
    ]
    for i, p in enumerate(profiles):
        bw_sitl = p.bandwidth_sitl(schema)
        bw_c50c = p.bandwidth_c50c(schema)
        out += [
            f"    {p.name!r}: LogProfile(",
            f"        id=LogProfileId.{p.name.upper()},",
            f"        name={p.name!r},",
            f"        description={p.description!r},",
            f"        bandwidth_c50c={bw_c50c},",
            f"        bandwidth_sitl={bw_sitl},",
            "        entries=(",
        ]
        for entry in p.entries:
            msg = msg_map[entry.topic]
            tid = msg_ids[entry.topic]
            rate_kind = "LogRateKind.EVERY_SAMPLE" if entry.rate == "every_sample" else (
                "LogRateKind.AS_PUBLISHED" if entry.rate == "as_published" else "LogRateKind.RATE_HZ"
            )
            out.append(
                f"            LogProfileEntry(topic={entry.topic!r}, topic_id={tid}, "
                f"instance={entry.instance!r}, rate_kind={rate_kind}, rate_hz={entry.rate_hz(msg)}, "
                f"wire_bytes={wire_bytes(msg.encoded_size)}, instance_count={entry.instance_count(msg)}, "
                f"kconfig={entry.kconfig!r}),"
            )
        out += [
            "        ),",
            "    ),",
        ]
    out += [
        "}",
        "BY_ID = {p.id: p for p in PROFILES.values()}",
        "",
    ]
    return "\n".join(out)


def outputs(schema: Schema, profiles: list[Profile] | None = None) -> dict[str, str]:
    """Generated files keyed by their path relative to the output directory."""
    messages = schema.messages
    files = {f"vk/msg/{m.name}.hpp": message_header(m, topic_id) for topic_id, m in enumerate(messages)}
    files["vk/msg/wire.hpp"] = wire_header()
    files["vk/msg/topics.hpp"] = topics_header(messages)
    files["vk/msg/enums.hpp"] = enums_header(schema.enums)
    files["python/vkmsg.py"] = python_module(messages)
    files["python/vkenums.py"] = python_enums(schema.enums)
    files["vk/msg/registry.hpp"] = registry_header()
    files["vk/msg/registry.cpp"] = registry_source(messages)
    if profiles is not None:
        files["vk/msg/log_profiles.hpp"] = log_profiles_header(profiles, schema)
        files["vk/link/log_profile_streams.hpp"] = log_profile_streams_header(profiles, schema)
        files["python/vklog_profiles.py"] = python_log_profiles(profiles, schema)
        files["python/vkformats.py"] = python_ulog_formats(schema)
    return files

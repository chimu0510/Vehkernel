def ulog_field(field: Field) -> str:
    ulog_types = {
        "bool": "bool",
        "int8": "int8_t",
        "int16": "int16_t",
        "int32": "int32_t",
        "int64": "int64_t",
        "uint8": "uint8_t",
        "uint16": "uint16_t",
        "uint32": "uint32_t",
        "uint64": "uint64_t",
        "float32": "float",
        "float64": "double",
    }
    base = ulog_types[field.type]
    if field.length is not None:
        return f"{base}[{field.length}] {field.name}"
    return f"{base} {field.name}"


def message_ulog_format(msg: Message) -> str:
    fields = ";".join(ulog_field(f) for f in msg.fields)
    return f"{msg.name}:{fields};"



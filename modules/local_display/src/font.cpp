constexpr std::array<Glyph, glyph_count> glyph_columns()
{
    std::array<Glyph, glyph_count> glyphs{};
    for (std::size_t g = 0; g < glyph_count; ++g) {
        for (std::size_t row = 0; row < font_height; ++row) {
            for (std::size_t column = 0; column < font_width; ++column) {
                if (glyph_rows.at(g).at(row).at(column) == '#') {
                    glyphs.at(g).at(column) = static_cast<std::uint8_t>(glyphs.at(g).at(column) | (1U << row));
                }
            }
        }
    }
    return glyphs;
}

constexpr std::array<Glyph, glyph_count> glyphs = glyph_columns();

static_assert(glyphs.at('A' - first_glyph).at(0) == 0x7E, "the first column of A is lit from row 1 to row 6");


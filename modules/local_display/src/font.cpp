const Glyph& glyph(char c)
{
    const auto code = static_cast<unsigned char>(c);
    if (code < first_glyph || code >= first_glyph + glyph_count) {
        return glyphs.at('?' - first_glyph);
    }
    return glyphs.at(code - first_glyph);
}

